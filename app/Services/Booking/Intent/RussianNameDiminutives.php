    /** @var array<string, string[]>|null */
    private static ?array $index = null;

    /**
     * @return string[] canonical full names this diminutive could belong to, empty if unknown
     */
    public static function fullNamesFor(string $token): array
    {
        $key = Str::lower(trim($token));

        if ($key === '') {
            return [];
        }

        return self::index()[$key] ?? [];
    }

    /** @return array<string, string[]> */
    private static function index(): array
    {
        if (self::$index !== null) {
            return self::$index;
        }

        $index = [];

        foreach (self::MAP as $full => $diminutives) {
            foreach ($diminutives as $diminutive) {
                $index[$diminutive][] = $full;
            }
        }

        return self::$index = $index;
    }
